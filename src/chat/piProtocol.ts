/* ---------------------------------------------------------------- the gate */

/**
 * The prefix of the title of every `ctx.ui.confirm` our gate extension sends.
 * A dialog without it is somebody else's extension and is answered "cancelled".
 */
export const piGatePrefix = 'AI Browser gate: ';

/** The command the gate registers; its presence in `get_commands` proves the extension loaded. */
export const piGateCommand = 'aib-gate';

/**
 * The extension AI Browser loads into every Pi process it starts (`-e <file>`;
 * Pi runs `.ts` itself, measured). It does two things and holds no secret:
 *
 * - **Gate**: `pi.on('tool_call')` asks the chat through `ctx.ui.confirm`
 *   — which in rpc mode is an `extension_ui_request` — before *every* tool,
 *   built in or MCP. Pi has no approval of its own, so without this it runs
 *   `bash`, `edit` and `write` unasked. A handler that throws blocks the tool
 *   (measured: fail-safe), and so does ours on any error. If the extension
 *   fails to load Pi runs WITHOUT the gate (an `extension_error` event), which
 *   is why the session checks `get_commands` for `aib-gate` and refuses to
 *   send a message otherwise.
 * - **Browser tools**: when the chat has its MCP server running it registers
 *   it with `registerMcpServer`, `exposure: 'direct'` (without it the model
 *   never sees the tools, measured). The URL, token and chat capability come
 *   from the child's environment through `${VAR}` substitution in the headers
 *   (measured), so the file on disk is the same for everybody and the token is
 *   in no argument and no file.
 *
 * Plain JavaScript, no types: Pi's loader strips none and needs none.
 */
export const piGateExtension = `// AI Browser: the approval gate and the browser tools for a Pi process started by the chat.
// Generated by the extension; it holds no secret and is rewritten when its text changes.
export default function (pi) {
  pi.registerCommand(${JSON.stringify(piGateCommand)}, {
    description: "AI Browser approval gate (always on in the chat)",
    handler: async (_args, ctx) => { ctx.ui.notify("The AI Browser approval gate is active.", "info"); },
  });
  const url = process.env.AIB_MCP_URL;
  if (url && process.env.AIB_MCP_TOKEN) {
    const headers = { Authorization: "Bearer \${AIB_MCP_TOKEN}" };
    if (process.env.AIB_CHAT) headers["X-AI-Browser-Chat"] = "\${AIB_CHAT}";
    if (process.env.AIB_TAB) headers["X-AI-Browser-Tab"] = "\${AIB_TAB}";
    pi.registerMcpServer("ai-browser", { url, headers, exposure: "direct", description: "AI Browser: the browser, the editor and the chat" });
  }
  pi.on("tool_call", async (event, ctx) => {
    try {
      const allowed = await ctx.ui.confirm(${JSON.stringify(piGatePrefix)} + event.toolName, JSON.stringify({ id: event.toolCallId, input: event.input }));
      if (allowed !== true) return { block: true, reason: "Denied by the user." };
    } catch {
      return { block: true, reason: "The approval could not be asked." };
    }
    return undefined;
  });
}
`;

/** A gate question, read from an `extension_ui_request`. */
export interface PiGateRequest {
	/** The id the answer goes back under. */
	readonly requestId: string;
	/** Pi's own tool name: `bash`, `edit`, `mcp__ai_browser__browser_state`. */
	readonly tool: string;
	/** The call's id, when the extension could read it. */
	readonly callId?: string;
	/** The arguments as the model wrote them; `{}` when they could not be read. */
	readonly input: Readonly<Record<string, unknown>>;
}

export function piGateRequest(message: Record<string, unknown>): PiGateRequest | undefined {
	if (message.type !== 'extension_ui_request' || message.method !== 'confirm' || typeof message.id !== 'string') {
		return undefined;
	}
	const title = typeof message.title === 'string' ? message.title : '';
	if (!title.startsWith(piGatePrefix) || title.length === piGatePrefix.length) {
		return undefined;
	}
	let input: Record<string, unknown> = {};
	let callId: string | undefined;
	try {
		const body: unknown = JSON.parse(typeof message.message === 'string' ? message.message : '{}');
		if (isRecord(body)) {
			if (isRecord(body.input)) { input = body.input; }
			if (typeof body.id === 'string') { callId = body.id; }
		}
	} catch { /* the arguments are shown as `{}`: the card still names the tool */ }
	return { requestId: message.id, tool: title.slice(piGatePrefix.length), ...(callId ? { callId } : {}), input };
}

/** What the answer to a dialog looks like on stdin. */
export function piUiResponse(requestId: string, answer: boolean | 'cancel'): Record<string, unknown> {
	return answer === 'cancel'
		? { type: 'extension_ui_response', id: requestId, cancelled: true }
		: { type: 'extension_ui_response', id: requestId, confirmed: answer };
}

/** A dialog method that waits for an answer; a dialog from an extension of ours is not among them. */
export function piIsDialog(message: Record<string, unknown>): boolean {
	return message.type === 'extension_ui_request' && typeof message.id === 'string'
		&& ['select', 'confirm', 'input', 'editor'].includes(String(message.method));
}

/**
 * Pi's tool as Claude Code's `can_use_tool` would name it, so the chat's one
 * classifier (`claudeApproval`: Terminal, Files in or outside the project,
 * AI Browser, Chat control, MCP · server, Other tools) decides the card and
 * the approval menu's category. `readOnly` calls — read, grep, find, ls — are
 * what Claude Code never asks about inside the project, and `path` is what the
 * outside-the-project test is run on.
 */
export function piGateTool(tool: string, input: Readonly<Record<string, unknown>>): { readonly toolName: string; readonly input: Record<string, unknown>; readonly readOnly: boolean; readonly path?: string } {
	const str = (key: string) => typeof input[key] === 'string' ? input[key] as string : undefined;
	// Pi resolves a path as `normalizePath(…, { normalizeUnicodeSpaces, stripAtPrefix })` before it touches
	// the file, so `@/etc/hosts` is `/etc/hosts` to Pi and a project-relative name to `outsideProject`.
	// The card and the inside-the-project test must see the path Pi will use (measured against Pi 1.4.0).
	const file = (key: string): string | undefined => {
		const raw = str(key);
		if (raw === undefined) { return undefined; }
		const spaced = raw.replace(/[\u00A0\u2000-\u200A\u202F\u205F\u3000]/g, ' ');
		return spaced.startsWith('@') ? spaced.slice(1) : spaced;
	};
	switch (tool) {
		case 'read': return { toolName: 'Read', input: { file_path: file('path') ?? '' }, readOnly: true, path: file('path') ?? '' };
		case 'bash': return { toolName: 'Bash', input: { command: str('command') ?? '' }, readOnly: false };
		case 'edit': return { toolName: 'Edit', input: { file_path: file('path') ?? '' }, readOnly: false, path: file('path') ?? '' };
		case 'write': return { toolName: 'Write', input: { file_path: file('path') ?? '', content: str('content') ?? '' }, readOnly: false, path: file('path') ?? '' };
		case 'grep': return { toolName: 'Grep', input: { pattern: str('pattern') ?? '', path: file('path') ?? '.' }, readOnly: true, path: file('path') ?? '.' };
		case 'find': return { toolName: 'Glob', input: { pattern: str('pattern') ?? str('name') ?? '', path: file('path') ?? '.' }, readOnly: true, path: file('path') ?? '.' };
		case 'ls': return { toolName: 'Glob', input: { pattern: '*', path: file('path') ?? '.' }, readOnly: true, path: file('path') ?? '.' };
		default: break;
	}
	const mcp = piMcpName(tool);
	if (mcp) {
		// Our own server is registered as `ai-browser`, which Pi writes `ai_browser`.
		return { toolName: `mcp__${mcp.server === 'ai_browser' ? 'ai-browser' : mcp.server}__${mcp.tool}`, input: { ...input }, readOnly: false };
	}
	return { toolName: tool || 'Tool', input: { ...input }, readOnly: false };
}

/**
 * `mcp__<server>__<tool>` as Pi names an MCP tool (non-alphanumerics of the
 * server become `_`: `ai-browser` is `ai_browser`, measured). Undefined when it
 * is not one, or when `__` appears more than once after the prefix — such a
 * name cannot be split for sure, and the approval treats it as Other tools.
 */
export function piMcpName(tool: string): { readonly server: string; readonly tool: string } | undefined {
	const match = /^mcp__(.+?)__(.+)$/.exec(tool);
	if (!match) { return undefined; }
	const rest = tool.slice('mcp__'.length);
	if (rest.indexOf('__') !== rest.lastIndexOf('__')) { return undefined; }
	return { server: match[1], tool: match[2] };
}

/* ------------------------------------------------------------------ models */

/**
 * The thinking levels a model offers, lowest first. Measured: a model with
 * `reasoning: true` offers the levels its `thinkingLevelMap` does not set to
 * `null` (gpt-5-mini: minimal to high; gpt-5.6-luna: off, low to max; o3: low to
 * high — each equal to `get_available_thinking_levels` for that model as
 * current), and a model with `reasoning: false` offers `off` only, which is no
 * choice at all. A reasoning model with no map is not measured: it is given
 * low, medium and high.
 */
export function piThinkingLevels(model: unknown): string[] {
	if (!isRecord(model) || model.reasoning !== true) { return []; }
	const map = isRecord(model.thinkingLevelMap) ? model.thinkingLevelMap : undefined;
	if (!map) { return ['low', 'medium', 'high']; }
	const levels = piThinkingOrder.filter(level => level in map && map[level] !== null);
	return levels.length > 1 ? levels : [];
}

/** The id the chat uses for a model: Pi's models are listed across providers, so the provider is part of it. */
export function piModelRef(model: { readonly provider: string; readonly id: string }): string {
	return `${model.provider}/${model.id}`;
}

/** Splits `provider/id` at the first `/` (an id can hold more, `vendor/model` on a router). */
export function splitPiModel(ref: string): { readonly provider: string; readonly id: string } | undefined {
	const at = ref.indexOf('/');
	return at > 0 && at < ref.length - 1 ? { provider: ref.slice(0, at), id: ref.slice(at + 1) } : undefined;
}

/**
 * The chat's models from `get_available_models`, with `get_state`'s model as the
 * default. **The list is only what the login can see, not what works**: with a
 * ChatGPT-account login Pi lists every OpenAI model and a turn on an
 * unsupported one fails after it is sent (gpt-5-mini, gpt-5.5 — the user's own
 * default — measured failing; gpt-5.6-luna, gpt-6-luna, gpt-6.1-terra working).
 * Pi has no way to say which, so `piErrorText` says what to do when one fails.
 */
export function piModels(list: unknown, current?: unknown): ChatModel[] {
	const models = isRecord(list) && Array.isArray(list.models) ? list.models : Array.isArray(list) ? list : [];
	const currentRef = isRecord(current) && typeof current.provider === 'string' && typeof current.id === 'string' && current.id !== 'unknown'
		? piModelRef({ provider: current.provider, id: current.id }) : undefined;
	const rows = models.filter(isRecord).filter(m => typeof m.provider === 'string' && typeof m.id === 'string' && m.id);
	const nameCount = new Map<string, number>();
	for (const m of rows) { const name = typeof m.name === 'string' && m.name.trim() ? m.name.trim() : String(m.id); nameCount.set(name, (nameCount.get(name) ?? 0) + 1); }
	const out: ChatModel[] = [];
	for (const m of rows) {
		const ref = piModelRef({ provider: m.provider as string, id: m.id as string });
		if (out.some(o => o.id === ref)) { continue; }
		const name = typeof m.name === 'string' && m.name.trim() ? m.name.trim() : String(m.id);
		const efforts = piThinkingLevels(m);
		const window = typeof m.contextWindow === 'number' && m.contextWindow > 0 ? `${Math.round(m.contextWindow / 1000)}K context` : undefined;
		out.push({
			id: ref,
			label: (nameCount.get(name) ?? 0) > 1 ? `${name} · ${m.provider}` : name,
			description: [m.provider, window].filter(Boolean).join(' · '),
			efforts,
			...(efforts.includes(piDefaultThinking) ? { defaultEffort: piDefaultThinking } : {}),
			isDefault: ref === currentRef,
		});
	}
	if (out.length && !out.some(m => m.isDefault)) {
		out[0] = { ...out[0], isDefault: true };
	}
	return out;
}

/** A model's context window from a model object (`get_state`, `set_model`, the list), for the pie. */
export function piContextWindow(model: unknown): number | undefined {
	return isRecord(model) && typeof model.contextWindow === 'number' && model.contextWindow > 0 ? model.contextWindow : undefined;
}

/**
 * Skills and prompt templates from `get_commands`, typed as `/name` (a skill is
 * `/skill:<name>`, measured; this user's own skills are listed). Commands
 * registered by extensions — Pi's own `mcp` and `llama`, our `aib-gate` — are not
 * the user's and are left out, as are the TUI's built-ins, which Pi does not list.
 */
export function piCommands(list: unknown): ChatCommand[] {
	const commands = isRecord(list) && Array.isArray(list.commands) ? list.commands : [];
	const out: ChatCommand[] = [];
	for (const c of commands) {
		if (!isRecord(c) || typeof c.name !== 'string' || !c.name || c.source === 'extension' || out.some(o => o.name === c.name)) { continue; }
		const info = isRecord(c.sourceInfo) ? c.sourceInfo : {};
		const description = typeof c.description === 'string' && c.description.trim() ? clipText(c.description.replace(/\s+/g, ' ').trim(), 500) : undefined;
		out.push({ name: c.name, insert: `/${c.name}`, ...(description ? { description } : {}), group: info.scope === 'project' ? 'project' : 'user' });
	}
	return out;
}

/** Whether the commands prove our gate loaded (`piGateCommand` is registered by the extension). */
export function piGateLoaded(list: unknown): boolean {
	const commands = isRecord(list) && Array.isArray(list.commands) ? list.commands : [];
	return commands.some(c => isRecord(c) && c.name === piGateCommand);
}

