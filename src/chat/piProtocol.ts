/** The text of a result: Pi's tool results are `{ content: [{ type: 'text', text }] }`. */
export function piResultText(result: unknown): string {
	if (typeof result === 'string') { return result; }
	if (!isRecord(result) || !Array.isArray(result.content)) { return ''; }
	return result.content
		.map(part => isRecord(part) && part.type === 'text' && typeof part.text === 'string' ? part.text : isRecord(part) && part.type === 'image' ? '[image]' : '')
		.filter(Boolean).join('\n');
}

const outputLimit = 20_000;

/** A tool's output kept for its row; a `cat` of a large file is not worth keeping whole. */
function clip(text: string): string {
	return text.length > outputLimit ? `${text.slice(0, outputLimit)}\n… ${text.length - outputLimit} more characters not kept.` : text;
}

function clipText(text: string, limit: number): string {
	return text.length > limit ? `${text.slice(0, limit - 1)}…` : text;
}

/** How a Pi tool call reads on its row, from the arguments measured on 1.4.0 (`read`, `bash`, `write`, `edit`; `grep`, `find`, `ls` only with `--tools`). */
export function piTool(name: string, args: unknown): ToolStart {
	const i = isRecord(args) ? args : {};
	const str = (key: string) => typeof i[key] === 'string' ? i[key] as string : undefined;
	switch (name) {
		case 'read': return { kind: 'read', name: 'Read', detail: str('path') };
		case 'bash': return { kind: 'command', name: 'Bash', input: str('command') };
		case 'write': {
			const lines = (str('content') ?? '').split('\n');
			return { kind: 'edit', name: 'Write', detail: str('path'), input: lines.map(l => `+${l}`).join('\n'), added: lines.length, removed: 0 };
		}
		case 'edit': {
			const edits = Array.isArray(i.edits) ? i.edits.filter(isRecord) : [];
			const lines: string[] = [];
			let added = 0, removed = 0;
			for (const e of edits) {
				for (const l of String(e.oldText ?? '').split('\n')) { lines.push(`-${l}`); removed++; }
				for (const l of String(e.newText ?? '').split('\n')) { lines.push(`+${l}`); added++; }
			}
			return { kind: 'edit', name: 'Edit', detail: str('path'), input: lines.join('\n'), added, removed };
		}
		case 'grep':
		case 'find':
		case 'ls':
			return { kind: 'search', name: name[0].toUpperCase() + name.slice(1), detail: [str('pattern') && `"${str('pattern')}"`, str('path')].filter(Boolean).join(' in ') || undefined };
		default: break;
	}
	const mcp = piMcpName(name);
	const body = Object.keys(i).length ? JSON.stringify(i, null, 2) : undefined;
	if (mcp) {
		return { kind: 'mcp', name: `${mcp.server === 'ai_browser' ? 'ai-browser' : mcp.server} · ${mcp.tool}`, ...(body ? { input: body } : {}) };
	}
	return { kind: 'other', name, ...(body ? { input: body } : {}) };
}

/** Counts the lines a unified diff adds and removes (headers excluded). */
export function patchCounts(patch: string): { added: number; removed: number } {
	let added = 0, removed = 0;
	for (const line of patch.split('\n')) {
		if (line.startsWith('+++') || line.startsWith('---')) { continue; }
		if (line.startsWith('+')) { added++; } else if (line.startsWith('-')) { removed++; }
	}
	return { added, removed };
}

/** The tokens one assistant message used, in the chat's terms; undefined when it reports none. */
function messageUsage(message: Record<string, unknown>): { input: number; output: number; cached: number; total: number; cost?: number } | undefined {
	const u = isRecord(message.usage) ? message.usage : undefined;
	if (!u) { return undefined; }
	const n = (v: unknown) => typeof v === 'number' && Number.isFinite(v) ? v : 0;
	const cacheRead = n(u.cacheRead), cacheWrite = n(u.cacheWrite);
	const total = n(u.totalTokens) || n(u.input) + n(u.output) + cacheRead + cacheWrite;
	const cost = isRecord(u.cost) && typeof u.cost.total === 'number' && Number.isFinite(u.cost.total) ? u.cost.total : undefined;
	// `input` excludes cache reads in Pi (216 + 1408 cached, measured); the chat's "sent" includes them.
	return total ? { input: n(u.input) + cacheRead + cacheWrite, output: n(u.output), cached: cacheRead, total, ...(cost !== undefined ? { cost } : {}) } : undefined;
}

/**
 * Reads one session's stream into the chat's events. Hold one per Pi process
 * and feed it every message that is not a `response` or a dialog.
 *
 * What the stream does, measured on 1.4.0 (`samples`, the test file):
 * - a run is `agent_start` … `agent_settled`, the real end; `agent_end` is not
 *   (steer, follow-up and a retry continue after it). `agent_settled.aborted`
 *   tells a user's Stop from an error.
 * - a turn's messages: a system `message_start` (the whole system prompt — never
 *   shown), the user's, then each assistant response with its tool calls. A run
 *   with two tools is three assistant messages, each with its own `usage`
 *   (**per request**, cost already in USD): they are summed into one `tokens`.
 * - each text block is separate (`text_start`); thinking arrives as
 *   `thinking_start`/`thinking_end`, with `content` filled at the end and no
 *   `thinking_delta` (OpenAI), so the end's text is the thought.
 * - errors after Pi accepted the prompt are in the stream: an assistant
 *   `message_end` with `stopReason: 'error'` and `errorMessage`.
 */
export class PiEventReader {
	private _tokens = { input: 0, output: 0, cached: 0, cost: 0, hasCost: false, any: false };
	private _error: string | undefined;
	private _thoughtDelta = new Set<number>();
	private readonly _calls = new Map<string, string>();
	/** The user pressed Stop: a tool that ends in error ended because of it. */
	public stopping = false;
	/** The model's context window, for the pie; set from `get_state` / `set_model`. */
	public window: number | undefined;

	public read(message: Record<string, unknown>): AgentEvent[] {
		switch (message.type) {
			case 'message_update': return this._update(message);
			case 'message_end': return this._messageEnd(message);
			case 'tool_execution_start': {
				const id = typeof message.toolCallId === 'string' ? message.toolCallId : undefined;
				const name = typeof message.toolName === 'string' ? message.toolName : '';
				if (!id || !name) { return []; }
				this._calls.set(id, name);
				return [{ type: 'tool', id, tool: piTool(name, message.args) }];
			}
			case 'tool_execution_update': {
				const id = typeof message.toolCallId === 'string' ? message.toolCallId : undefined;
				const text = piResultText(message.partialResult);
				// A running bash reports its whole output so far, not a chunk.
				return id && text ? [{ type: 'toolUpdate', id, update: { output: clip(text) } }] : [];
			}
			case 'tool_execution_end': return this._toolEnd(message);
			case 'auto_retry_start': {
				const delay = typeof message.delayMs === 'number' ? ` in ${Math.max(1, Math.round(message.delayMs / 1000))} s` : '';
				const attempt = typeof message.attempt === 'number' && typeof message.maxAttempts === 'number' ? ` (attempt ${message.attempt} of ${message.maxAttempts})` : '';
				const why = typeof message.errorMessage === 'string' ? `: ${clipText(message.errorMessage.split('\n')[0], 200)}` : '';
				// Documented, not produced: no 429 or 5xx was measured.
				return [{ type: 'notice', text: `Pi is trying the request again${delay}${attempt}${why}` }];
			}
			case 'compaction_start':
				return [{ type: 'notice', text: 'Pi is compacting the conversation to free context…' }];
			case 'compaction_end': {
				if (message.aborted === true) { return []; }
				// A failed or empty compaction is measured ("Nothing to compact (session too small)"); a successful one is not.
				if (typeof message.errorMessage === 'string' && message.errorMessage) { return [{ type: 'notice', text: clipText(message.errorMessage, 300) }]; }
				return [{ type: 'context', compacted: true }, { type: 'notice', text: 'Conversation compacted.' }];
			}
			case 'extension_ui_request':
				// Pi reports a failed MCP server as a warning notification (measured).
				if (message.method === 'notify' && typeof message.message === 'string' && message.notifyType !== 'info') {
					return [{ type: 'notice', text: clipText(message.message.trim(), 600) }];
				}
				return [];
			case 'agent_settled': return this.settle(message.aborted === true);
			default: return [];
		}
	}

	/** The events that end a run: its tokens, then the end, with the error when there was one. */
	public settle(aborted: boolean): AgentEvent[] {
		const events: AgentEvent[] = [];
		const t = this._tokens;
		if (t.any) {
			events.push({ type: 'tokens', input: t.input, output: t.output, cached: t.cached, ...(t.hasCost ? { costUsd: t.cost } : {}), cumulative: false });
		}
		const error = aborted || this.stopping ? 'Stopped.' : this._error ? piErrorText(this._error) : undefined;
		events.push({ type: 'turnEnd', ...(error ? { error } : {}) });
		this.reset();
		return events;
	}

	public reset(): void {
		this._tokens = { input: 0, output: 0, cached: 0, cost: 0, hasCost: false, any: false };
		this._error = undefined;
		this._thoughtDelta.clear();
		this._calls.clear();
		this.stopping = false;
	}

	private _update(message: Record<string, unknown>): AgentEvent[] {
		const e = isRecord(message.assistantMessageEvent) ? message.assistantMessageEvent : undefined;
		if (!e) { return []; }
		const index = typeof e.contentIndex === 'number' ? e.contentIndex : -1;
		switch (e.type) {
			case 'text_start': return [{ type: 'textBreak' }];
			case 'text_delta': return typeof e.delta === 'string' && e.delta ? [{ type: 'text', text: e.delta }] : [];
			case 'thinking_start': this._thoughtDelta.delete(index); return [];
			case 'thinking_delta':
				if (typeof e.delta !== 'string' || !e.delta) { return []; }
				this._thoughtDelta.add(index);
				return [{ type: 'thinking', text: e.delta }];
			case 'thinking_end':
				return typeof e.content === 'string' && e.content.trim() && !this._thoughtDelta.has(index) ? [{ type: 'thinking', text: e.content }] : [];
			default: return [];
		}
	}

	private _messageEnd(message: Record<string, unknown>): AgentEvent[] {
		const m = isRecord(message.message) ? message.message : undefined;
		if (!m || m.role !== 'assistant') { return []; }
		const events: AgentEvent[] = [];
		const usage = messageUsage(m);
		if (usage) {
			const t = this._tokens;
			t.input += usage.input; t.output += usage.output; t.cached += usage.cached; t.any = true;
			if (usage.cost !== undefined) { t.cost += usage.cost; t.hasCost = true; }
			// The latest request's total is what the next one carries (1672 after the measured turn).
			events.push({ type: 'context', used: usage.total, ...(this.window ? { window: this.window } : {}) });
		}
		if (m.stopReason === 'error' && typeof m.errorMessage === 'string' && m.errorMessage) {
			this._error = m.errorMessage;
		}
		return events;
	}

	private _toolEnd(message: Record<string, unknown>): AgentEvent[] {
		const id = typeof message.toolCallId === 'string' ? message.toolCallId : undefined;
		if (!id) { return []; }
		const name = this._calls.get(id) ?? (typeof message.toolName === 'string' ? message.toolName : '');
		const result = isRecord(message.result) ? message.result : {};
		const text = piResultText(result);
		const failed = message.isError === true;
		const status = failed ? (this.stopping ? 'stopped' as const : 'failed' as const) : 'done' as const;
		const structured = isRecord(result.structuredContent) ? result.structuredContent : undefined;
		const exitCode = name === 'bash' && structured && typeof structured.exit_code === 'number' ? structured.exit_code : undefined;
		const details = isRecord(result.details) ? result.details : undefined;
		// `edit` returns a ready unified diff (measured), better than the one built from its arguments.
		const patch = name === 'edit' && details && typeof details.patch === 'string' ? details.patch : undefined;
		const counts = patch ? patchCounts(patch) : undefined;
		return [{
			type: 'toolUpdate', id,
			update: {
				status, output: clip(text),
				// Pi's bash exits non-zero without `isError`; the row shows it as failed all the same.
				...(exitCode !== undefined ? { exitCode } : {}),
				...(patch ? { input: clip(patch), added: counts!.added, removed: counts!.removed } : {}),
			},
		}, ...(exitCode !== undefined && exitCode !== 0 && !failed ? [{ type: 'toolUpdate' as const, id, update: { status: 'failed' as const } }] : [])];
	}
}

/** `get_state`'s data, or undefined: model, level, session id and file. */
export function piState(response: unknown): { readonly model?: Record<string, unknown>; readonly thinkingLevel?: string; readonly sessionId?: string; readonly streaming: boolean } | undefined {
	const data = isRecord(response) && isRecord(response.data) ? response.data : undefined;
	if (!data) { return undefined; }
	return {
		...(isRecord(data.model) ? { model: data.model } : {}),
		...(typeof data.thinkingLevel === 'string' ? { thinkingLevel: data.thinkingLevel } : {}),
		...(typeof data.sessionId === 'string' ? { sessionId: data.sessionId } : {}),
		streaming: data.isStreaming === true,
	};
}

/** `get_state` with no login: model `unknown` (measured), and `get_available_models` is empty. */
export function piSignedOut(state: unknown, models: readonly unknown[]): boolean {
	if (models.length) { return false; }
	const model = piState(state)?.model;
	return !model || model.id === 'unknown' || model.provider === 'unknown';
}

/** Whether a `response` is a failure, and Pi's words for it. */
export function piResponseError(response: Record<string, unknown>): string | undefined {
	return response.success === false ? (typeof response.error === 'string' && response.error ? response.error : 'Pi refused the request.') : undefined;
}

/** `/compact` typed alone: the chat runs Pi's own `compact` command for it. */
export function isCompactRequest(text: string): boolean {
	return /^\/compact\s*$/i.test(text.trim());
}

function isRecord(value: unknown): value is Record<string, unknown> {
	return typeof value === 'object' && value !== null && !Array.isArray(value);
}
