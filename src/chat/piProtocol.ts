export interface PiStartOptions {
	readonly provider?: string;
	readonly modelId?: string;
	readonly thinking?: string;
	/** `--session-id`: creates the session with exactly this id, or resumes it (measured). */
	readonly sessionId?: string;
	/** The gate's extension file; absent only for a probe that sends no prompt. */
	readonly extension?: string;
	/** `--no-approve`: ignore project-local files (`.pi/`); set for a folder that was not trusted. */
	readonly noApprove: boolean;
	/** AGENTS.md / CLAUDE.md are read into the system prompt unless this is false. */
	readonly contextFiles: boolean;
	/** A probe keeps no session file. */
	readonly noSession?: boolean;
}

/**
 * The arguments of `pi --mode rpc`. The model is always passed explicitly:
 * Pi's own default (the user's `defaultModel`) failed on the measured account.
 * No `--session-dir`, so the session lands where a plain `pi --session <id>` in
 * a terminal finds it.
 */
export function piArgs(options: PiStartOptions): string[] {
	const args = ['--mode', 'rpc'];
	if (options.provider && options.modelId) { args.push('--provider', options.provider, '--model', options.modelId); }
	if (options.thinking && (piThinkingOrder as readonly string[]).includes(options.thinking)) { args.push('--thinking', options.thinking); }
	if (options.noSession) { args.push('--no-session'); }
	else if (options.sessionId) { args.push('--session-id', options.sessionId); }
	if (options.extension) { args.push('-e', options.extension); }
	if (!options.contextFiles) { args.push('--no-context-files'); }
	if (options.noApprove) { args.push('--no-approve'); }
	return args;
}

/** The environment that hands the browser server to the gate extension; none while the server is off. */
export function piMcpEnv(server: { readonly url: string; readonly token: string } | undefined, chat: string | undefined, tab: string | undefined): Record<string, string> {
	return server ? {
		AIB_MCP_URL: server.url, AIB_MCP_TOKEN: server.token,
		...(chat ? { AIB_CHAT: chat } : {}), ...(tab ? { AIB_TAB: tab } : {}),
	} : {};
}

/** What resumes a conversation in a terminal, run in its folder (from another folder Pi asks to fork it). */
export function piResumeArgs(ref: string): string[] {
	return ['--session', ref];
}

/* ------------------------------------------------------------------ errors */

export const piSignedOutText = 'Pi is not signed in: no provider has credentials. Sign in with “Sign in” on the agent (it runs pi; type /login there), or set a provider key such as OPENAI_API_KEY in the environment VS Code was started with, then press Refresh Agents.';

/**
 * A Pi error as the chat shows it, with what to do next. The wording is ours;
 * the cause is Pi's, kept in front of it so nothing is hidden. Measured: a
 * missing login (`No API key found for the selected model.`) and a model the
 * login cannot use (`model_not_found … not supported when using Codex with a
 * ChatGPT account`). Rate limits, overload and authentication failures after a
 * login are read from Pi's retry documentation and from the shapes other
 * agents see, not produced here.
 */
export function piErrorText(text: string): string {
	const raw = text.trim();
	const first = clipText(raw.split('\n')[0] ?? raw, 400);
	if (/No API key found|credentials_not_configured|No models available|\/login/i.test(raw) && !/model_not_found/i.test(raw)) {
		return piSignedOutText;
	}
	if (/model_not_found|not supported when using|Model not found|does not exist|unknown model/i.test(raw)) {
		return `${first} Pi lists models its login cannot always use. Pick another model, press Refresh Agents, or change the login in a terminal with pi and /login.`;
	}
	if (/\b(401|403)\b|invalid[_ ]api[_ ]?key|unauthorized|authentication/i.test(raw)) {
		return `${first} Pi is not authenticated for this model: sign in again with pi and /login, or check the provider key, then press Refresh Agents.`;
	}
	if (/\b429\b|rate.?limit|too many requests|quota/i.test(raw)) {
		return `${first} The provider is limiting requests or the quota is used up. Wait and send again, or pick another model.`;
	}
	if (/\b(500|502|503|504|529)\b|overloaded|unavailable|ECONNRESET|ETIMEDOUT|fetch failed/i.test(raw)) {
		return `${first} The provider or the network failed. Send the message again, or pick another model.`;
	}
	return clipText(raw, 800) || 'Pi reported an error.';
}

/** What a Pi process that ended says: stderr's tail, or the exit. */
export function piExitText(reason: string, starting: boolean): string {
	if (/env: node: No such file or directory|node: command not found/i.test(reason)) {
		return 'Pi needs Node.js 22.19 or newer, and none was found. Install Node.js, or start VS Code from a terminal, then press Refresh Agents.';
	}
	return starting ? `Pi did not start. ${clipText(reason, 600)}` : `Pi stopped. ${clipText(reason, 600)} The next message starts it again and resumes this conversation.`;
}

